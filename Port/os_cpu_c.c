#define  OS_CPU_CM_FPCCR_LAZY_STK                         0xC0000000uL   /* 参见注意 (1)                              */
/*
*********************************************************************************************************
*                                       系统初始化钩子函数（起始处）
*
* 描述：此函数在 OSInit() 的开始阶段被调用。
*
* 参数：无
*
* 注意：1) 在此函数被调用期间，中断应保持关闭状态。
*       2) 使用硬件浮点单元时，请在复位处理程序中完成以下操作：
*          a) 在 CPACR 寄存器中设置 CP10 和 CP11 为完全访问权限。
*          b) 在 FPCCR 寄存器中设置 ASPEN 和 LSPEN 位。
*********************************************************************************************************
*/
#if OS_CPU_HOOKS_EN > 0u
void  OSInitHookBegin (void)
{
    INT32U   size;
    OS_STK  *pstk;
#if (OS_CPU_ARM_FP_EN > 0u)
    INT32U   reg_val;
#endif
                                                                /* 清空异常栈，以便进行栈检查。*/
    pstk = &OS_CPU_ExceptStk[0];
    size = OS_CPU_EXCEPT_STK_SIZE;
    while (size > 0u) {
        size--;
       *pstk++ = (OS_STK)0;
    }

                                                                /* 将 ISR 栈对齐到 8 字节边界 */
    OS_CPU_ExceptStkBase = (OS_STK *)&OS_CPU_ExceptStk[OS_CPU_EXCEPT_STK_SIZE];
    OS_CPU_ExceptStkBase = (OS_STK *)((OS_STK)(OS_CPU_ExceptStkBase) & 0xFFFFFFF8);

#if (OS_CPU_ARM_FP_EN > 0u)
    reg_val = OS_CPU_CM_FP_FPCCR;                               /* 检查浮点单元模式。          */
    if ((reg_val & OS_CPU_CM_FPCCR_LAZY_STK) != OS_CPU_CM_FPCCR_LAZY_STK) {
        while (1u) {                                            /* 参见注意 (2)                */
            ;
        }
    }
#endif

#if OS_TMR_EN > 0u
    OSTmrCtr = 0u;
#endif

                                                                /* 从配置中设置 BASEPRI 边界值 */
    OS_KA_BASEPRI_Boundary = (INT32U)(CPU_CFG_KA_IPL_BOUNDARY << (8u - CPU_CFG_NVIC_PRIO_BITS));
}
#endif
